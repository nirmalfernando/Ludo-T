-- LUDO-T Online schema. Portable between PostgreSQL (Supabase) and H2 in PostgreSQL mode.
-- The server's memory is authoritative while a game runs; these tables are its durable log.

CREATE TABLE IF NOT EXISTS players (
    id          VARCHAR(36) PRIMARY KEY,
    nickname    VARCHAR(16) NOT NULL,
    created_at  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS rooms (
    id            VARCHAR(16) PRIMARY KEY,
    mode          VARCHAR(10) NOT NULL CHECK (mode IN ('PLAY', 'BOT_MATCH')),
    variant       VARCHAR(10) NOT NULL CHECK (variant IN ('CLASSIC', 'LUDO_T')),
    seed          BIGINT      NOT NULL,
    status        VARCHAR(10) NOT NULL CHECK (status IN ('WAITING', 'RUNNING', 'PAUSED', 'FINISHED', 'CLOSED')),
    host_id       VARCHAR(36) REFERENCES players (id),
    winner_colour VARCHAR(6),
    total_turns   INT         NOT NULL DEFAULT 0,
    created_at    TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at   TIMESTAMP
);

CREATE TABLE IF NOT EXISTS seats (
    room_id     VARCHAR(16) NOT NULL REFERENCES rooms (id) ON DELETE CASCADE,
    colour      VARCHAR(6)  NOT NULL CHECK (colour IN ('YELLOW', 'BLUE', 'RED', 'GREEN')),
    player_id   VARCHAR(36) REFERENCES players (id),
    controller  VARCHAR(12) NOT NULL CHECK (controller IN ('FREE', 'HUMAN', 'AI', 'AFK', 'DISCONNECTED')),
    PRIMARY KEY (room_id, colour)
);

-- One row per applied step of a game: a roll (option_index NULL) or a move (the chosen option).
-- turn_number is the engine's step counter, so the primary key makes a duplicate step impossible
-- at the database level, a second line of defence behind the room's own validation.
CREATE TABLE IF NOT EXISTS decisions (
    room_id      VARCHAR(16) NOT NULL REFERENCES rooms (id) ON DELETE CASCADE,
    turn_number  INT         NOT NULL,
    colour       VARCHAR(6)  NOT NULL,
    roll         INT         CHECK (roll BETWEEN 1 AND 6),
    option_index INT,
    source       VARCHAR(10) NOT NULL CHECK (source IN ('HUMAN', 'AI', 'TIMEOUT', 'AUTO_SKIP')),
    decided_at   TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (room_id, turn_number)
);

-- An archive of chat as clients saw it; channel_seq keeps the order. room_id is NULL for lobby chat.
CREATE TABLE IF NOT EXISTS chat_messages (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id     VARCHAR(16)  REFERENCES rooms (id) ON DELETE CASCADE,
    channel_seq BIGINT       NOT NULL,
    player_id   VARCHAR(36)  REFERENCES players (id),
    text        VARCHAR(200) NOT NULL,
    is_system   BOOLEAN      NOT NULL DEFAULT FALSE,
    sent_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_rooms_finished ON rooms (status, finished_at);
CREATE INDEX IF NOT EXISTS idx_chat_room_seq ON chat_messages (room_id, channel_seq);
